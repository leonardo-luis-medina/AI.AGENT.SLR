import hashlib
import html
import json
import os
from datetime import datetime, timezone

import requests
from dotenv import load_dotenv

load_dotenv()

HUBSPOT_API = "https://api.hubapi.com"
TIMEOUT = 30

NOTE_TO_DEAL_ASSOCIATION_TYPE = 214


def build_qc_note(deal_id: str, qc_result: dict) -> str:
    """Build an HTML-safe HubSpot note containing the QC results."""

    summary = qc_result.get("summary", {})
    fingerprint = qc_fingerprint(deal_id, qc_result)

    lines = [
        "SolarQC - Automated Quality Control",
        f"Deal: {deal_id}",
        f"Fingerprint: {fingerprint}",
        f"Overall Status: {qc_result.get('overall_status', 'UNKNOWN')}",
        "",
        "QC Summary:",
        f"PASS: {summary.get('PASS', 0)}",
        f"FAIL: {summary.get('FAIL', 0)}",
        f"NEEDS_HUMAN: {summary.get('NEEDS_HUMAN', 0)}",
        "",
        "Rule Results:",
    ]

    for result in qc_result.get("results", []):
        rule = result.get("rule", result.get("rule_id", "UNKNOWN"))
        status = result.get("status", "UNKNOWN")
        reason = result.get("reason", result.get("message", ""))

        lines.append(f"{rule}: {status} - {reason}")

    lines.extend(
        [
            "",
            "Generated by SolarQC.",
            "Demo QC rules only; not a regulatory certification.",
        ]
    )

    return "<br>".join(html.escape(str(line)) for line in lines)


def qc_fingerprint(deal_id: str, qc_result: dict) -> str:
    """Create a stable fingerprint for identical QC evaluations."""

    relevant_data = {
        "deal_id": deal_id,
        "overall_status": qc_result.get("overall_status"),
        "summary": qc_result.get("summary", {}),
        "results": qc_result.get("results", []),
    }

    serialized = json.dumps(
        relevant_data,
        sort_keys=True,
        default=str,
    )

    return hashlib.sha256(serialized.encode()).hexdigest()[:16]


def _headers() -> dict:
    token = os.getenv("HUBSPOT_ACCESS_TOKEN")

    if not token:
        raise ValueError("HUBSPOT_ACCESS_TOKEN is missing.")

    return {
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
    }


def resolve_hubspot_deal_id(solarqc_deal_id: str) -> str:
    """Find the unique HubSpot deal matching a SolarQC demo ID."""

    response = requests.post(
        f"{HUBSPOT_API}/crm/v3/objects/deals/search",
        headers=_headers(),
        json={
            "filterGroups": [
                {
                    "filters": [
                        {
                            "propertyName": "solarqc_deal_id",
                            "operator": "EQ",
                            "value": solarqc_deal_id,
                        }
                    ]
                }
            ],
            "properties": ["solarqc_deal_id"],
            "limit": 2,
        },
        timeout=TIMEOUT,
    )

    response.raise_for_status()
    matches = response.json().get("results", [])

    if not matches:
        raise ValueError(
            f"SolarQC deal {solarqc_deal_id} not found in HubSpot."
        )

    if len(matches) > 1:
        raise ValueError(
            f"Multiple HubSpot deals match {solarqc_deal_id}."
        )

    match = matches[0]
    properties = match.get("properties", {})

    if properties.get("solarqc_deal_id") != solarqc_deal_id:
        raise ValueError("HubSpot deal identity verification failed.")

    hubspot_id = str(match.get("id", ""))

    if not hubspot_id.isdigit():
        raise ValueError("HubSpot returned an invalid deal ID.")

    return hubspot_id


def find_existing_qc_note(
    hubspot_deal_id: str,
    fingerprint: str,
) -> str | None:
    """Check associated notes for a matching SolarQC fingerprint."""

    if not str(hubspot_deal_id).isdigit():
        raise ValueError("HubSpot deal ID must be numeric.")

    marker = f"Fingerprint: {fingerprint}"
    after = None

    while True:
        params = {"limit": 100}

        if after:
            params["after"] = after

        response = requests.get(
            (
                f"{HUBSPOT_API}/crm/v3/objects/deals/"
                f"{hubspot_deal_id}/associations/notes"
            ),
            headers=_headers(),
            params=params,
            timeout=TIMEOUT,
        )

        response.raise_for_status()
        data = response.json()

        for association in data.get("results", []):
            note_id = str(association.get("id", ""))

            if not note_id.isdigit():
                continue

            note_response = requests.get(
                f"{HUBSPOT_API}/crm/v3/objects/notes/{note_id}",
                headers=_headers(),
                params={"properties": "hs_note_body"},
                timeout=TIMEOUT,
            )

            note_response.raise_for_status()

            note_body = (
                note_response.json()
                .get("properties", {})
                .get("hs_note_body", "")
            )

            if marker in note_body:
                return note_id

        after = data.get("paging", {}).get("next", {}).get("after")

        if not after:
            return None


def create_hubspot_note(
    hubspot_deal_id: str,
    note_body: str,
) -> dict:
    """Create a HubSpot note associated with a verified deal."""

    if not str(hubspot_deal_id).isdigit():
        raise ValueError("HubSpot deal ID must be numeric.")

    timestamp_ms = int(
        datetime.now(timezone.utc).timestamp() * 1000
    )

    payload = {
        "properties": {
            "hs_timestamp": timestamp_ms,
            "hs_note_body": note_body,
        },
        "associations": [
            {
                "to": {"id": str(hubspot_deal_id)},
                "types": [
                    {
                        "associationCategory": "HUBSPOT_DEFINED",
                        "associationTypeId": NOTE_TO_DEAL_ASSOCIATION_TYPE,
                    }
                ],
            }
        ],
    }

    response = requests.post(
        f"{HUBSPOT_API}/crm/v3/objects/notes",
        headers=_headers(),
        json=payload,
        timeout=TIMEOUT,
    )

    response.raise_for_status()
    return response.json()